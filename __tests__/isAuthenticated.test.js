import jwt from 'jsonwebtoken';
import mongoose from 'mongoose';
import User from '../models/User'; 
import { verifyTokenMiddleware } from '../index'; 

jest.mock('jsonwebtoken');
jest.mock('mongoose');

describe('Verify Token Middleware', () => {
  let req, res, next;

  beforeEach(() => {
    req = {
      cookies: {
        token: 'dummyToken'
      },
      user: null
    };
    res = {
      redirect: jest.fn()
    };
    next = jest.fn();
  });

  it('should call next if token is valid', async () => {
    const mockUser = { _id: 'userId' };
    jwt.verify.mockReturnValueOnce(mockUser);
    mongoose.model('User').findById.mockResolvedValueOnce(mockUser);

    await verifyTokenMiddleware(req, res, next);

    expect(req.user).toEqual(mockUser);
    expect(next).toHaveBeenCalled();
    expect(res.redirect).not.toHaveBeenCalled();
  });

  it('should redirect to login if token is not present', async () => {
    req.cookies = {};

    await verifyTokenMiddleware(req, res, next);

    expect(res.redirect).toHaveBeenCalledWith('/login');
    expect(next).not.toHaveBeenCalled();
  });

  it('should redirect to login if token is invalid', async () => {
    jwt.verify.mockImplementationOnce(() => {
      throw new Error('invalid token');
    });

    await verifyTokenMiddleware(req, res, next);

    expect(res.redirect).toHaveBeenCalledWith('/login');
    expect(next).not.toHaveBeenCalled();
  });
});
